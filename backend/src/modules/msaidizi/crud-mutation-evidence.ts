export function crudMutationAuditScopeKind(
  company: CrudMutationAuditCompanyContract,
): Extract<CrudFixtureAuditScopeKind, 'COMPANY' | 'GLOBAL'> {
  return company.kind === 'exact' && 'literal' in company.value && company.value.literal === null
    ? 'GLOBAL'
    : 'COMPANY';
}

