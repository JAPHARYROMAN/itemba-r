export type CrudMutationPrimitive = string | number | boolean | null;

export type CrudMutationValue =
  | { literal: CrudMutationPrimitive }
  | { binding: string; path?: readonly string[] }
  /** Resolves to `${prefix}-${12 lowercase hex characters}`; no implicit truncation. */
  | { unique: { prefix: string } }
  | { now: 'iso' }
  | { array: readonly CrudMutationValue[] }
  | { object: Readonly<Record<string, CrudMutationValue>> };

/** Values available only while verifying an effect after the HTTP response. */
export type CrudMutationEffectValue =
  | CrudMutationValue
  /** Path is evaluated against the standard unwrapped response payload. */
  | { response: { path: readonly string[] } }
  /** References the persisted row (or its id when path is absent) of an earlier named effect. */
  | { effectRef: { effectId: string; path?: readonly string[] } };

/**
 * Closed-world validators for scalar values generated by a create service.
 * These fields are deliberately separate from request-backed expectedFields:
 * a fixture must explain who generated each value and how it is checked.
 */
export type CrudMutationGeneratedField =
  | {
      kind: 'exact';
      value: CrudMutationValue;
    }
  | {
      kind: 'action-time';
      offsetMs?: number;
    }
  | {
      /** Local calendar-day arithmetic (Date.setDate), which is DST-aware. */
      kind: 'action-local-calendar-days';
      offsetDays: number;
    }
  | {
      /** Exact local midnight derived from a signed ISO/date request value. */
      kind: 'local-day-start';
      value: CrudMutationValue;
    }
  | {
      /** Exact final millisecond of the local day derived from a signed ISO/date request value. */
      kind: 'local-day-end';
      value: CrudMutationValue;
    }
  | {
      /** Exact UTC midnight derived from a signed ISO/date request value. */
      kind: 'utc-day-start';
      value: CrudMutationValue;
    }
  | {
      /** Exact final millisecond of the UTC day derived from a signed ISO/date request value. */
      kind: 'utc-day-end';
      value: CrudMutationValue;
    }
  | {
      /**
       * Recomputed from persisted source rows, never from the action response.
       * The loopback verifier owns the independent domain calculation.
       */
      kind: 'independent-domain-aggregate';
      source: 'customer-statement' | 'supplier-statement' | 'financial-trial-balance';
    }
  | {
      /**
       * Proves a one-time response secret against its persisted digest without
       * serializing either value into the signed evidence artifact.
       */
      kind: 'response-secret-digest';
      /** Path within the controller payload, after the global HTTP envelope. */
      responsePath: readonly string[];
      algorithm: 'sha256' | 'hmac-sha256-app-encryption-key';
      encoding: 'hex';
    }
  | {
      /** Proves a non-secret generated scalar against an exact response value. */
      kind: 'response-exact';
      responsePath: readonly string[];
    }
  | {
      /** Proves a persisted secret prefix without writing the response secret to evidence. */
      kind: 'response-secret-prefix';
      responsePath: readonly string[];
      length: number;
    }
  | {
      /** Verifies a one-way password hash against a signed request value in memory only. */
      kind: 'request-secret-hash';
      requestPath: readonly string[];
      algorithm: 'argon2';
    }
  | {
      kind: 'timestamp-id';
      prefix: string;
      timestampEncoding: 'decimal' | 'base36-upper';
      actionLocalCalendarYear?: {
        separator: string;
      };
      randomSuffix?: {
        alphabet: 'base36-upper' | 'hex-upper';
        length: number;
        separator: string;
      };
    }
  | {
      kind: 'value-with-prefix';
      value: CrudMutationValue;
      prefix: string;
      suffix?: string;
    }
  | {
      kind: 'value-with-action-iso-suffix';
      value: CrudMutationValue;
      separator: string;
      suffix?: string;
    }
  | {
      /** Exact idempotency number emitted by TaxAutoApplyService per source line. */
      kind: 'tax-auto-apply-number';
      sourcePrefix: 'SALES' | 'PURCHASE';
      sourceId: CrudMutationValue;
      sourceLineId: CrudMutationValue;
      fragmentLength: 8;
    }
  | {
      /**
       * EntityCodeGeneratorService.next side effect. The loopback runner must
       * prove and recover the exact DocumentNumberSequence delta.
       */
      kind: 'entity-code';
      entityType: string;
      companyId?: CrudMutationValue;
    }
  | {
      /** A deterministic counter derived from the captured pre-action model rows. */
      kind: 'scoped-sequence-id';
      separator: string;
      prefixParts: readonly (
        | { kind: 'literal'; value: string }
        | { kind: 'action-year' }
        | {
            kind: 'company-code';
            companyId: CrudMutationValue;
            preferredField: 'employeeCodePrefix';
            fallbackField: 'code';
            fallbackLength: number;
          }
        | { kind: 'company-id-fragment'; companyId: CrudMutationValue; length: number }
      )[];
      scope: Readonly<Record<string, CrudMutationValue>>;
      counter: {
        strategy: 'count-scope' | 'count-prefix' | 'first-unused-prefix';
        padding: number;
      };
    };

