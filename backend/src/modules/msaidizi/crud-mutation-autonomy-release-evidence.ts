function sequenceEffect(spec: SequenceSpec): CrudMutationCompoundNamedEffect {
  return {
    effectId: spec.effectId,
    kind: 'scoped-row-create',
    model: 'DocumentNumberSequence',
    scope: {
      equals: { companyId: spec.companyId, entityType: literal(spec.entityType) },
      identityFields: ['id'],
    },
    expectedFields: {
      companyId: spec.companyId,
      entityType: literal(spec.entityType),
      prefix: literal(spec.prefix),
      suffix: literal(null),
      currentNumber: literal(1),
      padding: literal(spec.padding),
      resetFrequency: literal('YEARLY'),
      isActive: literal(true),
      deletedAt: literal(null),
    },
    generatedFields: {
      sequenceCode: {
        kind: 'value-with-prefix',
        prefix: `${spec.entityType}_`,
        value: spec.companyId,
      },
      lastResetAt: { kind: 'action-time' },
    },
    allowedFields: ['id', 'createdAt', 'updatedAt'],
    recovery: 'restore-scope',
    recoveryOrder: spec.recoveryOrder,
  };
}

function journalEffect(spec: JournalSpec): CrudMutationCompoundNamedEffect {
  const status = spec.status ?? 'POSTED';
  return {
    effectId: spec.effectId,
    kind: 'scoped-row-create',
    model: 'JournalEntry',
    scope: {
      equals: { companyId: spec.companyId, referenceType: literal(spec.referenceType) },
      identityFields: ['id'],
    },
    expectedFields: {
      companyId: spec.companyId,
      divisionId: spec.divisionId ?? literal(null),
      branchId: spec.branchId ?? literal(null),
      accountingPeriodId: spec.accountingPeriodId,
      transactionDate: spec.transactionDate,
      description: spec.description,
      referenceType: literal(spec.referenceType),
      referenceId: spec.referenceId,
      status: literal(status),
      totalDebit: spec.total,
      totalCredit: spec.total,
      createdById: userA,
      postedById: status === 'POSTED' ? userA : literal(null),
      postedAt: status === 'POSTED' ? spec.transactionDate : literal(null),
      reversedById: literal(null),
      reversedAt: literal(null),
      reversalReason: literal(null),
      reversalOfId: literal(null),
      deletedAt: literal(null),
    },
    generatedFields: { journalNumber: spec.journalNumber },
    allowedFields: ['id', 'createdAt', 'updatedAt'],
    recovery: 'restore-scope',
    recoveryOrder: spec.recoveryOrder,
  };
}

