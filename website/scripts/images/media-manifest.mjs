#!/usr/bin/env node
/**
 * Writes src/content/media.generated.ts: intrinsic width/height and a tiny
 * blurDataURL for every image under public/images, keyed by its public src
 * ("/images/<folder>/<file>.webp"). src/content/media.ts (the hand-written
 * registry) and the Media UI component read it, so next/image gets real
 * dimensions and a blur placeholder without static imports.
 *
 * Deterministic: files are sorted and sharp's output for identical input is
 * stable, so re-running on unchanged images produces a byte-identical file.
 * The image pipeline (scripts/images/build-images.mjs, WP1.4) calls
 * writeMediaManifest() after re-exporting the masters.
 *
 * Usage: npm run media:manifest   (or: node scripts/images/media-manifest.mjs --check)
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const IMAGES_DIR = path.join(ROOT, 'public', 'images');
const OUT_FILE = path.join(ROOT, 'src', 'content', 'media.generated.ts');
const IMAGE_EXT = /\.(webp|jpe?g|png|avif)$/i;
/** Longest edge of the blur placeholder, in pixels. */
const BLUR_SIZE = 16;

async function listImages(dir, prefix = '') {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await listImages(path.join(dir, entry.name), rel)));
    else if (IMAGE_EXT.test(entry.name)) files.push(rel);
  }
  return files;
}

async function describe(file) {
  const input = await readFile(path.join(IMAGES_DIR, file));
  const meta = await sharp(input).metadata();
  // EXIF orientations 5–8 are rotated by 90°; browsers render them upright.
  const rotated = (meta.orientation ?? 1) >= 5;
  const width = rotated ? meta.height : meta.width;
  const height = rotated ? meta.width : meta.height;
  const blur = await sharp(input)
    .rotate()
    .resize(BLUR_SIZE, BLUR_SIZE, { fit: 'inside' })
    .webp({ quality: 40, effort: 6 })
    .toBuffer();
  return { src: `/images/${file}`, width, height, blurDataURL: `data:image/webp;base64,${blur.toString('base64')}` };
}

export async function buildMediaManifest() {
  const files = await listImages(IMAGES_DIR);
  const rows = [];
  for (const file of files) rows.push(await describe(file));
  const body = rows
    .map(
      (r) =>
        `  ${JSON.stringify(r.src)}: {\n    width: ${r.width},\n    height: ${r.height},\n    blurDataURL:\n      ${JSON.stringify(r.blurDataURL)},\n  },`,
    )
    .join('\n');
  return [
    '// GENERATED by scripts/images/media-manifest.mjs (npm run media:manifest). Do not edit by hand.',
    '// Intrinsic size and a small blur placeholder for every image under public/images, keyed by public src.',
    "import 'server-only';",
    '',
    'export type GeneratedMedia = { readonly width: number; readonly height: number; readonly blurDataURL: string };',
    '',
    'export const mediaGenerated = {',
    body,
    '} as const satisfies Record<string, GeneratedMedia>;',
    '',
    'export type GeneratedMediaSrc = keyof typeof mediaGenerated;',
    '',
  ].join('\n');
}

export async function writeMediaManifest() {
  const text = await buildMediaManifest();
  await writeFile(OUT_FILE, text, 'utf8');
  return OUT_FILE;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const [expected, actual] = await Promise.all([buildMediaManifest(), readFile(OUT_FILE, 'utf8').catch(() => '')]);
    if (expected !== actual) {
      console.error('[media:manifest] src/content/media.generated.ts is stale. Run `npm run media:manifest`.');
      process.exit(1);
    }
    console.log('[media:manifest] up to date.');
  } else {
    const out = await writeMediaManifest();
    console.log(`[media:manifest] wrote ${path.relative(ROOT, out)}`);
  }
}
